#!/usr/bin/env bash
# One-time setup: generates the Flutter platform folders and adds Second Look's native code.
# Requires: Flutter SDK (3.22+). For iOS also Xcode 15+ and CocoaPods.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

if [ ! -d android ] || [ ! -d ios ] || [ ! -d web ]; then
  flutter create --org com.secondlook --project-name second_look --platforms android,ios,web .
fi

# Google's official TEST ad ids are used unless you pass your own (see docs/ADS_AND_PLUS.md).
ADMOB_APP_ID_ANDROID="${ADMOB_APP_ID_ANDROID:-ca-app-pub-3940256099942544~3347511713}"
ADMOB_APP_ID_IOS="${ADMOB_APP_ID_IOS:-ca-app-pub-3940256099942544~1458002511}"

echo "→ Android: native code, engine and assets"
rm -f android/app/src/main/kotlin/com/secondlook/second_look/MainActivity.kt
cp -R android_overlay/app/src/main/. android/app/src/main/
mkdir -p android/app/src/main/java/com/secondlook/engine android/app/src/main/assets/secondlook
cp ../engine-java/src/com/secondlook/engine/Engine.java ../engine-java/src/com/secondlook/engine/Json.java \
   ../engine-java/src/com/secondlook/engine/LibPhoneLookup.java android/app/src/main/java/com/secondlook/engine/
cp ../shared/dist/rules.json ../shared/dist/phone_data.json android/app/src/main/assets/secondlook/
# Hindi / Kannada texts for notifications (the same file the Flutter UI reads)
cp assets/i18n/i18n.json android/app/src/main/assets/secondlook/i18n.json
cp android_overlay/app/proguard-rules.pro android/app/proguard-rules.pro
sed -i.bak "s|ADMOB_APP_ID_ANDROID_PLACEHOLDER|$ADMOB_APP_ID_ANDROID|" android/app/src/main/AndroidManifest.xml && rm -f android/app/src/main/AndroidManifest.xml.bak

echo "→ Android: integrity fingerprints (the app refuses to run if these files are changed)"
sha() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }
RULES_SHA=$(sha android/app/src/main/assets/secondlook/rules.json)
PHONE_SHA=$(sha android/app/src/main/assets/secondlook/phone_data.json)
CERT_SHA=$(echo "${SECONDLOOK_CERT_SHA256:-}" | tr -d ': ' | tr 'A-F' 'a-f')
cat > android/app/src/main/java/com/secondlook/second_look/Integrity.java <<JAVA
package com.secondlook.second_look;

/** Generated by tool/setup.sh — do not edit. */
final class Integrity {
    private Integrity() { }
    static final String RULES_SHA256 = "$RULES_SHA";
    static final String PHONE_DATA_SHA256 = "$PHONE_SHA";
    static final String SIGNING_CERT_SHA256 = "$CERT_SHA";
}
JAVA

GRADLE=android/app/build.gradle.kts
[ -f "$GRADLE" ] || GRADLE=android/app/build.gradle
# Call screening needs Android 10 (API 29) or newer.
sed -i.bak -E 's/minSdk(Version)? *=? *flutter\.minSdkVersion/minSdk = 29/' "$GRADLE" && rm -f "$GRADLE.bak"
if ! grep -q libphonenumber "$GRADLE"; then
  if [[ "$GRADLE" == *.kts ]]; then
    printf '\ndependencies {\n    implementation("com.googlecode.libphonenumber:libphonenumber:8.13.27")\n}\n' >> "$GRADLE"
  else
    printf "\ndependencies {\n    implementation 'com.googlecode.libphonenumber:libphonenumber:8.13.27'\n}\n" >> "$GRADLE"
  fi
fi
# On-device screenshot reading: ML Kit text recognition (Latin) + QR scanning, with the models BUNDLED in the
# app (no Google Play services download, nothing uploaded).
if ! grep -q "com.google.mlkit:text-recognition" "$GRADLE"; then
  if [[ "$GRADLE" == *.kts ]]; then
    printf '\ndependencies {\n    implementation("com.google.mlkit:text-recognition:16.0.1")\n    implementation("com.google.mlkit:barcode-scanning:17.3.0")\n}\n' >> "$GRADLE"
  else
    printf "\ndependencies {\n    implementation 'com.google.mlkit:text-recognition:16.0.1'\n    implementation 'com.google.mlkit:barcode-scanning:17.3.0'\n}\n" >> "$GRADLE"
  fi
fi
grep -q "minSdk = 29" "$GRADLE" || echo "⚠ Set minSdk to 29 in $GRADLE by hand (defaultConfig)."

echo "→ iOS: engine bundle for the plugin"
cp ../shared/dist/secondlook_engine.js packages/secondlook_ios/ios/Assets/
cp ../shared/dist/secondlook_engine.js ios_extensions/MessageFilter/
# Face ID prompt text for the optional app lock
if [ -f ios/Runner/Info.plist ] && ! grep -q NSFaceIDUsageDescription ios/Runner/Info.plist; then
  perl -0pi -e 's|</dict>\s*</plist>|\t<key>NSFaceIDUsageDescription</key>\n\t<string>Use Face ID to unlock Second Look.</string>\n</dict>\n</plist>|' ios/Runner/Info.plist
fi
# Photo library + camera prompts for "Check a payment screenshot" (the picked image is read on the phone only)
if [ -f ios/Runner/Info.plist ] && ! grep -q NSPhotoLibraryUsageDescription ios/Runner/Info.plist; then
  perl -0pi -e 's|</dict>\s*</plist>|\t<key>NSPhotoLibraryUsageDescription</key>\n\t<string>Choose a screenshot to check it for scams. It\x27s read on your iPhone and never uploaded.</string>\n</dict>\n</plist>|' ios/Runner/Info.plist
fi
if [ -f ios/Runner/Info.plist ] && ! grep -q NSCameraUsageDescription ios/Runner/Info.plist; then
  perl -0pi -e 's|</dict>\s*</plist>|\t<key>NSCameraUsageDescription</key>\n\t<string>Take a photo of a QR code to check it before you pay. The photo stays on your iPhone.</string>\n</dict>\n</plist>|' ios/Runner/Info.plist
fi
# AdMob app id + Google's ad network id (needed by the ads SDK, or the app closes at launch)
if [ -f ios/Runner/Info.plist ] && ! grep -q GADApplicationIdentifier ios/Runner/Info.plist; then
  perl -0pi -e "s|</dict>\\s*</plist>|\t<key>GADApplicationIdentifier</key>\n\t<string>$ADMOB_APP_ID_IOS</string>\n\t<key>SKAdNetworkItems</key>\n\t<array>\n\t\t<dict>\n\t\t\t<key>SKAdNetworkIdentifier</key>\n\t\t\t<string>cstr6suwn9.skadnetwork</string>\n\t\t</dict>\n\t</array>\n</dict>\n</plist>|" ios/Runner/Info.plist
fi
sed -i.bak -E "s/^# platform :ios, '[0-9.]+'/platform :ios, '14.0'/" ios/Podfile 2>/dev/null && rm -f ios/Podfile.bak || true

echo "→ Laptop (web): the same JavaScript engine the iPhone app uses"
cp ../shared/dist/secondlook_engine.js web/secondlook_engine.js
if ! grep -q secondlook_engine.js web/index.html; then
  perl -0pi -e 's|</head>|  <script src="secondlook_engine.js"></script>\n</head>|' web/index.html
fi
perl -0pi -e 's|<title>[^<]*</title>|<title>Second Look</title>|; s|content="A new Flutter project."|content="Check any link, SMS or phone number for scams. Runs in your browser."|' web/index.html
if ! grep -q 'name="referrer"' web/index.html; then
  perl -0pi -e 's|<head>|<head>\n  <meta name="referrer" content="no-referrer">|' web/index.html
fi
[ -f web/manifest.json ] && perl -0pi -e 's|"name": "[^"]*"|"name": "Second Look"|; s|"short_name": "[^"]*"|"short_name": "Second Look"|; s|"description": "[^"]*"|"description": "Check any link, SMS or phone number for scams."|' web/manifest.json

flutter pub get
echo
echo "✓ Done. Android: flutter run   |   Laptop: flutter run -d chrome   |   iOS: open ios/Runner.xcworkspace and follow docs/IOS_SETUP.md"
